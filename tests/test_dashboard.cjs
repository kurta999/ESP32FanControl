'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(path.join(process.cwd(), '.pio/ui-test/node_modules/playwright-core'));
const base = (process.argv[2] || 'http://192.168.0.122').replace(/\/$/, '');
async function api(route, values) {
  const response = await fetch(base + route, values ? { method: 'POST', body: new URLSearchParams(values) } : {});
  assert.equal(response.status, 200, await response.clone().text());
  return response.json();
}
(async () => {
  const original = (await api('/api/status')).control;
  let browser;
  try {
    await api('/api/control', { auto_enabled: '0', strategy: 'threshold', curve: '35:0,40:30,50:65,60:100', curve_hysteresis_c: '1' });
    const executablePath = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe'].find(fs.existsSync);
    assert.ok(executablePath, 'Chrome executable missing');
    browser = await chromium.launch({ executablePath, headless: true, args: ['--no-proxy-server'] });
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base, { waitUntil: 'networkidle' });
    await page.waitForFunction(() => document.getElementById('temperature').textContent !== '--');
    assert.equal(await page.locator('#percent').getAttribute('max'), '100');
    assert.equal(await page.locator('#max_percent').getAttribute('max'), '100');
    for (const minutes of [5, 10, 20, 30]) {
      const response = page.waitForResponse(r => r.url().endsWith('/api/history?minutes=' + minutes));
      await page.locator('[data-minutes="' + minutes + '"]').click();
      assert.equal((await response).status(), 200);
      assert.equal(await page.locator('[data-minutes="' + minutes + '"]').getAttribute('aria-pressed'), 'true');
    }
    await page.locator('#percent').focus();
    await page.locator('#percent').press('End');
    assert.equal(await page.locator('#percent').inputValue(), '100');
    let response = page.waitForResponse(r => r.url().endsWith('/api/fan') && r.request().method() === 'POST');
    await page.locator('#apply').click();
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('applied').textContent === '100');
    response = page.waitForResponse(r => r.url().endsWith('/api/control') && r.request().method() === 'POST');
    await page.locator('#auto').check();
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('mode').textContent === 'Automatic');
    assert.ok(await page.locator('#percent').isDisabled());
    assert.ok(await page.locator('#apply').isDisabled());
    response = page.waitForResponse(r => r.url().endsWith('/api/control') && r.request().method() === 'POST');
    await page.locator('#auto').uncheck();
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('mode').textContent === 'Manual');
    response = page.waitForResponse(r => r.url().endsWith('/api/control') && r.request().method() === 'POST');
    await page.locator('#mode-select').selectOption('curve');
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('mode').textContent === 'Curve');
    assert.ok(await page.locator('#curve-card').isVisible());
    await page.waitForFunction(() => document.getElementById('curve-chart').dataset.temperature !== undefined);
    assert.ok(Number.isFinite(Number(await page.locator('#curve-chart').getAttribute('data-temperature'))));
    assert.equal(Number(await page.locator('#curve-chart').getAttribute('data-percent')), Number(await page.locator('#applied').textContent()));
    assert.ok((await page.locator('#curve-live-state').textContent()).includes('Applied fan'));
    const markerPixels = await page.locator('#curve-chart').evaluate(canvas => {
      const pixels = canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
      let count = 0;
      for (let i=0;i<pixels.length;i+=4) if(pixels[i]>230 && pixels[i+1]>150 && pixels[i+1]<230 && pixels[i+2]<150) count++;
      return count;
    });
    assert.ok(markerPixels > 20, 'Live amber guide/marker was not drawn');
    const pointCount = await page.locator('#curve-points .curve-row').count();
    await page.locator('#curve-add').click();
    assert.equal(await page.locator('#curve-points .curve-row').count(), pointCount + 1);
    await page.locator('#curve-points .curve-row').last().locator('button').click();
    assert.equal(await page.locator('#curve-points .curve-row').count(), pointCount);
    await page.locator('input[data-temperature]').first().fill('33');
    await page.locator('[data-duty]').last().fill('100');
    response = page.waitForResponse(r => r.url().endsWith('/api/control') && r.request().method() === 'POST');
    await page.locator('#curve-save').click();
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('message').textContent.includes('Curve saved'));
    assert.equal((await api('/api/status')).control.curve_points[0].temperature_c, 33);
    response = page.waitForResponse(r => r.url().endsWith('/api/fan/off') && r.request().method() === 'POST');
    await page.locator('#off').click();
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('value').textContent === 'Off');
    let stopped = await api('/api/status');
    assert.equal(stopped.applied_percent, 0);
    assert.equal(stopped.control.auto_enabled, false);
    assert.equal(stopped.control.manual_percent, 0);
    await page.waitForFunction(() => document.getElementById('curve-chart').dataset.percent === '0');
    response = page.waitForResponse(r => r.url().endsWith('/api/fan') && r.request().method() === 'POST');
    await page.locator('#apply').click();
    const restarted = await (await response).json();
    assert.equal(restarted.startup, true);
    response = page.waitForResponse(r => r.url().endsWith('/api/fan/off') && r.request().method() === 'POST');
    await page.locator('#off').click();
    stopped = await (await response).json();
    assert.equal(stopped.applied_percent, 0);
    assert.equal(stopped.startup, false);
    assert.equal(stopped.target_percent, 0);
    await page.waitForFunction(() => document.getElementById('applied').textContent === '0');
    await page.locator('#start_c').fill(await page.locator('#stop_c').inputValue());
    response = page.waitForResponse(r => r.url().endsWith('/api/control') && r.request().method() === 'POST');
    await page.locator('#save').click();
    assert.equal((await response).status(), 400);
    await page.waitForFunction(() => document.getElementById('message').textContent.includes('Require'));
    for (const key of ['stop_c','start_c','full_c','offset_c','min_percent','max_percent']) await page.locator('#' + key).fill(String(original[key]));
    response = page.waitForResponse(r => r.url().endsWith('/api/control') && r.request().method() === 'POST');
    await page.locator('#save').click();
    assert.equal((await response).status(), 200);
    await page.waitForFunction(() => document.getElementById('message').textContent.includes('saved to ESP32 flash'));
    await page.screenshot({ path: '.pio/dashboard-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '.pio/dashboard-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'Mobile layout overflows');
    assert.deepEqual(errors, []);
    console.log('Browser: live temperature, four graph intervals, manual 100%, three modes, curve add/remove/save/live operating marker, fan-off override/startup cancellation, validation, and mobile layout passed.');
  } finally {
    if (browser) await browser.close();
    await api('/api/control', { auto_enabled: '0' });
    await api('/api/fan', { percent: String(original.manual_percent) });
    const restored = {};
    for (const key of ['stop_c','start_c','full_c','offset_c','min_percent','max_percent']) restored[key] = String(original[key]);
    restored.auto_enabled = original.auto_enabled ? '1' : '0';
    restored.strategy = original.strategy;
    restored.curve_hysteresis_c = String(original.curve_hysteresis_c);
    restored.curve = original.curve_points.map(p => p.temperature_c + ':' + p.percent).join(',');
    await api('/api/control', restored);
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
